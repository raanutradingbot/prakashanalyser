import type { SymbolHit } from "../types";

/** Prefix match on symbol first, then substring match on name. */
export function searchSymbolIndex(index: SymbolHit[], query: string, limit: number): SymbolHit[] {
  const q = query.trim().toUpperCase();
  if (!q) return [];
  const starts: SymbolHit[] = [];
  const contains: SymbolHit[] = [];
  for (const entry of index) {
    if (entry.symbol.startsWith(q)) starts.push(entry);
    else if (entry.name.toUpperCase().includes(q)) contains.push(entry);
  }
  return [...starts, ...contains].slice(0, limit);
}

